"""Step 6b: EXPLORATORY segment results for conversion. Writes reports/06b_segments.md."""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.stats.multitest import multipletests

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from abtest.inference import benjamini_hochberg, heterogeneity_q, holm  # noqa: E402

TREATMENTS = {"Men's email": "Mens E-Mail", "Women's email": "Womens E-Mail"}
df = pd.read_csv(ROOT / "data" / "raw" / "hillstrom.csv")
df["purchase_history"] = np.select([(df.mens == 1) & (df.womens == 0), (df.mens == 0) & (df.womens == 1)],
                                   ["Men's only", "Women's only"], "Both")
df["recency_band"] = pd.cut(df.recency, [0, 3, 6, 9, 12], labels=["1-3 months", "4-6", "7-9", "10-12"])
df["new_customer"] = df.newbie.map({1: "New (last 12 months)", 0: "Existing"})
DIMS = {"Past purchases": "purchase_history", "Customer tenure": "new_customer", "Channel": "channel",
        "Area": "zip_code", "Recency": "recency_band", "Past-year spend": "history_segment"}

rows = []
for dname, col in DIMS.items():
    levels = df[col].cat.categories if hasattr(df[col], 'cat') else sorted(df[col].unique(), key=str)
    for level in levels:
        s = df[df[col] == level]
        c = s[s.segment == "No E-Mail"]
        for tlabel, seg in TREATMENTS.items():
            t = s[s.segment == seg]
            xt, nt, xc, nc = int(t.conversion.sum()), len(t), int(c.conversion.sum()), len(c)
            pt, pc = xt / nt, xc / nc
            se = np.sqrt(pt * (1 - pt) / nt + pc * (1 - pc) / nc)
            pp = (xt + xc) / (nt + nc)
            se0 = np.sqrt(pp * (1 - pp) * (1 / nt + 1 / nc))
            z = (pt - pc) / se0 if se0 > 0 else 0.0
            rows.append(dict(dimension=dname, segment=str(level), email=tlabel, n_t=nt, n_c=nc, buyers_t=xt,
                             buyers_c=xc, p_t=pt, p_c=pc, diff=pt - pc, se=se,
                             lo=pt - pc - 1.96 * se, hi=pt - pc + 1.96 * se, p=2 * stats.norm.sf(abs(z))))
res = pd.DataFrame(rows)
res["holm"] = holm(res.p)
res["bh"] = benjamini_hochberg(res.p)
assert np.allclose(res.holm, multipletests(res.p, method="holm")[1])
assert np.allclose(res.bh, multipletests(res.p, method="fdr_bh")[1])
m = len(res)

out = ["# Step 6b: segment results (EXPLORATORY)", "", "Generated by `python scripts/segments.py`.", "",
       "> **Exploratory only.** These cuts were not part of the decision rule. With "
       f"{m} segment × email tests, about {0.05 * m:.1f} would be 'significant' at p < 0.05 by chance alone "
       "even if every true effect were zero. Raw p-values are shown with Holm (family-wise error) and "
       "Benjamini-Hochberg (false discovery rate) corrections across all "
       f"{m} tests. A segment finding is a hypothesis for a new test, not a reason to target.", "",
       "Metric: conversion. Lift = treatment minus control in percentage points, 95% Wald CI. "
       "The **heterogeneity test** (Cochran's Q) asks whether the lift really differs across a dimension's "
       "levels; a segment can be significant on its own while the lifts are not different from each other.", ""]
het_rows = []
for dname in DIMS:
    for tlabel in TREATMENTS:
        g = res[(res.dimension == dname) & (res.email == tlabel)]
        het_rows.append((dname, tlabel, *heterogeneity_q(g["diff"], g.se)))
het_df = pd.DataFrame(het_rows, columns=["dimension", "email", "q", "dof", "p"])
het_df["holm"] = holm(het_df.p)

for dname in DIMS:
    sub = res[res.dimension == dname]
    out += [f"## {dname}", "", "| Segment | Email | n (T / C) | Buyers (T / C) | Lift (95% CI) | p | Holm p | BH p |",
            "|---|---|---|---|---|---|---|---|"]
    for _, r in sub.iterrows():
        out.append(f"| {r.segment} | {r.email} | {r.n_t:,} / {r.n_c:,} | {r.buyers_t} / {r.buyers_c} "
                   f"| {r['diff']*100:+.2f} pp ({r.lo*100:+.2f}, {r.hi*100:+.2f}) | {r.p:.3g} | {r.holm:.3g} | {r.bh:.3g} |")
    het = [f"{h.email}: Q = {h.q:.2f}, df = {h.dof}, p = {h.p:.3g} (Holm across {len(het_df)} heterogeneity tests: {h.holm:.3g})"
           for h in het_df[het_df.dimension == dname].itertuples()]
    out += ["", "Heterogeneity — " + "; ".join(het) + ".", ""]

n_raw, n_holm, n_bh = int((res.p < 0.05).sum()), int((res.holm < 0.05).sum()), int((res.bh < 0.05).sum())
out += ["## Summary", "", f"- Significant at p < 0.05: **{n_raw} of {m}** raw; **{n_holm}** after Holm; **{n_bh}** after BH.",
        f"- Heterogeneity tests with p < 0.05: **{int((het_df.p < 0.05).sum())} of {len(het_df)}** raw; "
        f"**{int((het_df.holm < 0.05).sum())}** after Holm across the {len(het_df)} heterogeneity tests.",
        f"- Smallest control cell: {res.buyers_c.min()} buyers. Cells with under 20 control buyers have rough "
        "normal-approximation CIs.", ""]
text = "\n".join(out)
(ROOT / "reports" / "06b_segments.md").write_text(text, encoding="utf-8", newline="\n")
print(text)
