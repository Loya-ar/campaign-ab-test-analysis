"""Step 4: main results. Writes reports/04_main_results.md."""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.stats.multitest import multipletests
from statsmodels.stats.proportion import proportions_ztest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from abtest.inference import bootstrap_diff_means, holm, two_proportion_test, welch_test  # noqa: E402

N_BOOT, SEED = 10_000, 2008
TREATMENTS = {"Men's email": "Mens E-Mail", "Women's email": "Womens E-Mail"}
df = pd.read_csv(ROOT / "data" / "raw" / "hillstrom.csv")
ctrl = df[df.segment == "No E-Mail"]
out = ["# Step 4: main results", "", "Generated by `python scripts/main_results.py`. Each email is "
       f"compared with the no-email group. 95% CIs. Holm correction across the 2 emails within each "
       f"metric. Bootstrap: {N_BOOT:,} resamples, seed {SEED}.", ""]


def pct(x):
    return f"{x:.3%}"


def proportion_section(metric, title):
    rows, ps = [], []
    for label, seg in TREATMENTS.items():
        t = df[df.segment == seg]
        r = two_proportion_test(int(t[metric].sum()), len(t), int(ctrl[metric].sum()), len(ctrl))
        sm_p = proportions_ztest([t[metric].sum(), ctrl[metric].sum()], [len(t), len(ctrl)])[1]
        assert np.isclose(r.p_value, sm_p, rtol=1e-6, atol=1e-300), (r.p_value, sm_p)
        rows.append((label, r)); ps.append(r.p_value)
    adj = holm(ps)
    assert np.allclose(adj, multipletests(ps, method="holm")[1])
    lines = [f"## {title}", "",
             "| Email | Treatment | Control | Absolute lift (95% CI) | Relative lift (95% CI) | z | p | Holm p |",
             "|---|---|---|---|---|---|---|---|"]
    for (label, r), a in zip(rows, adj):
        lines.append(
            f"| {label} | {pct(r.p_treatment)} | {pct(r.p_control)} "
            f"| {r.diff*100:+.3f} pp ({r.ci_diff[0]*100:+.3f}, {r.ci_diff[1]*100:+.3f}) "
            f"| {r.rel_lift:+.1%} ({r.ci_rel[0]:+.1%}, {r.ci_rel[1]:+.1%}) "
            f"| {r.z:.2f} | {r.p_value:.2e} | {a:.2e} |")
    return lines + [""]


def mean_section(title, filt=None, note=""):
    rows, ps = [], []
    c = ctrl if filt is None else ctrl[filt(ctrl)]
    for label, seg in TREATMENTS.items():
        t = df[df.segment == seg]
        t = t if filt is None else t[filt(t)]
        w = welch_test(t.spend, c.spend)
        sp = stats.ttest_ind(t.spend, c.spend, equal_var=False).pvalue
        assert np.isclose(w.p_value, sp, rtol=1e-6), (w.p_value, sp)
        _, bci, _ = bootstrap_diff_means(t.spend.values, c.spend.values, N_BOOT, seed=SEED)
        rows.append((label, len(t), len(c), w, bci)); ps.append(w.p_value)
    adj = holm(ps)
    lines = [f"## {title}", "", note, "",
             "| Email | n (T / C) | Treatment mean | Control mean | Difference | Welch 95% CI | Bootstrap 95% CI | Relative lift | p (Welch) | Holm p |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for (label, nt, nc, w, bci), a in zip(rows, adj):
        lines.append(
            f"| {label} | {nt:,} / {nc:,} | ${w.mean_treatment:.3f} | ${w.mean_control:.3f} | ${w.diff:+.3f} "
            f"| (${w.ci_diff[0]:+.3f}, ${w.ci_diff[1]:+.3f}) | (${bci[0]:+.3f}, ${bci[1]:+.3f}) "
            f"| {w.rel_lift:+.1%} | {w.p_value:.2e} | {a:.2e} |")
    return lines + [""]


out += proportion_section("conversion", "Primary: conversion rate")
out += proportion_section("visit", "Secondary: visit rate")
out += mean_section("Secondary: spend per customer",
                    note="All customers, non-buyers counted as $0. Median spend is $0 in every group, "
                         "so the bootstrap is a check on the t-based CI.")
out += mean_section("Guardrail: spend per buyer", filt=lambda d: d.conversion == 1,
                    note="Converters only. This is not a randomised comparison (who converts depends on "
                         "the email), so read it as a guardrail, not a causal effect.")

# Exploratory head-to-head (not in the planned analysis)
mens, womens = df[df.segment == "Mens E-Mail"], df[df.segment == "Womens E-Mail"]
h_conv = two_proportion_test(int(mens.conversion.sum()), len(mens), int(womens.conversion.sum()), len(womens))
h_spend = welch_test(mens.spend, womens.spend)
out += ["## Exploratory: men's email vs women's email", "",
        "Not part of the planned analysis (which compares each email with no email), so this is a "
        "pointer for the decision, not a confirmatory result.", "",
        f"- Conversion: men's minus women's = {h_conv.diff*100:+.3f} pp "
        f"(95% CI {h_conv.ci_diff[0]*100:+.3f} to {h_conv.ci_diff[1]*100:+.3f}), p = {h_conv.p_value:.2g}.",
        f"- Spend per customer: men's minus women's = ${h_spend.diff:+.3f} "
        f"(95% CI ${h_spend.ci_diff[0]:+.3f} to ${h_spend.ci_diff[1]:+.3f}), p = {h_spend.p_value:.2g}.", ""]

# Skew facts for the record
skew = df.groupby("segment").spend.agg(lambda s: (s > 0).mean())
out += ["## Data notes", "",
        f"- Spend skewness (all customers): {stats.skew(df.spend):.1f}. Share with any spend: "
        + ", ".join(f"{k} {v:.2%}" for k, v in skew.items()) + ".",
        "- p-values cross-checked against statsmodels `proportions_ztest`, SciPy `ttest_ind(equal_var=False)` "
        "and statsmodels `multipletests(method='holm')`; all match.", ""]

text = "\n".join(out)
(ROOT / "reports" / "04_main_results.md").write_text(text, encoding="utf-8", newline="\n")
print(text)
