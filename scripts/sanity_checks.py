"""Step 3: SRM and pre-period balance. Writes reports/03_sanity_checks.md. Uses no outcomes."""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import statsmodels.api as sm
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from abtest.checks import srm_test, standardized_mean_difference  # noqa: E402

GROUPS = ["No E-Mail", "Mens E-Mail", "Womens E-Mail"]
df = pd.read_csv(ROOT / "data" / "raw" / "hillstrom.csv")
out: list[str] = ["# Step 3: sanity checks", "", "Generated by `python scripts/sanity_checks.py`. "
                  "No outcome columns are used here.", ""]

# --- SRM -------------------------------------------------------------------
counts = df.segment.value_counts().reindex(GROUPS)
srm = srm_test(counts.tolist())
out += ["## Sample ratio mismatch", "", "Planned split: 1/3 per group.", "",
        "| Group | Observed | Expected | Share |", "|---|---|---|---|"]
for g, o, e in zip(GROUPS, srm.observed, srm.expected):
    out.append(f"| {g} | {o:,} | {e:,.1f} | {o/len(df):.3%} |")
out += ["", f"Chi-square = {srm.chi2:.3f}, df = 2, **p = {srm.p_value:.3f}**. "
        f"SRM flagged (p < 0.001)? **{'Yes' if srm.mismatch() else 'No'}**.", ""]
pair_lines = []
for t in GROUPS[1:]:
    r = srm_test([counts[t], counts["No E-Mail"]])
    pair_lines.append(f"- {t} vs No E-Mail (planned 50/50): chi-square {r.chi2:.3f}, p = {r.p_value:.3f}")
out += pair_lines + [""]

# --- Balance ---------------------------------------------------------------
X = pd.get_dummies(df[["zip_code", "channel"]], prefix=["zip", "channel"], dtype=float)
cov = pd.concat([df[["recency", "history", "mens", "womens", "newbie"]].astype(float), X], axis=1)
out += ["## Pre-period balance", "",
        "Standardized mean difference (SMD) of each treatment vs control; |SMD| < 0.1 is the usual bar. "
        "The p-value tests all three groups together: Kruskal-Wallis for `recency` and `history` "
        "(skewed), chi-square for binary columns. `mens` / `womens` = bought men's / women's "
        "merchandise in the past year; `Surburban` is the source file's spelling.", "",
        "| Covariate | Control mean | Men's mean | Women's mean | SMD men's | SMD women's | p (3 groups) |",
        "|---|---|---|---|---|---|---|"]
max_smd = 0.0
for col in cov.columns:
    parts = [cov.loc[df.segment == g, col] for g in GROUPS]
    smd_m = standardized_mean_difference(parts[1], parts[0])
    smd_w = standardized_mean_difference(parts[2], parts[0])
    max_smd = max(max_smd, abs(smd_m), abs(smd_w))
    if col in ("recency", "history"):
        p = stats.kruskal(*parts).pvalue
    else:
        p = stats.chi2_contingency(pd.crosstab(df.segment, cov[col]))[1]
    out.append(f"| {col} | {parts[0].mean():.3f} | {parts[1].mean():.3f} | {parts[2].mean():.3f} "
               f"| {smd_m:+.4f} | {smd_w:+.4f} | {p:.3f} |")
out += ["", f"Largest |SMD|: **{max_smd:.4f}**.", ""]

# Omnibus: can the pre-period features predict assignment at all?
Xo = cov.drop(columns=["zip_Rural", "channel_Multichannel"])  # drop reference levels
Xo = sm.add_constant(Xo)
y = pd.Categorical(df.segment, categories=GROUPS).codes
fit = sm.MNLogit(y, Xo).fit(disp=False)
out += ["## Omnibus test", "",
        "Multinomial logistic regression of group on all pre-period features. If randomisation "
        "worked, the features should not predict assignment.", "",
        f"Likelihood-ratio chi-square = {fit.llr:.2f}, df = {int(fit.df_model)}, **p = {fit.llr_pvalue:.3f}**; "
        f"pseudo R-squared = {fit.prsquared:.6f}.", ""]

text = "\n".join(out)
(ROOT / "reports").mkdir(exist_ok=True)
(ROOT / "reports" / "03_sanity_checks.md").write_text(text, encoding="utf-8", newline="\n")
print(text)
