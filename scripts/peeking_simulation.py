"""Step 6a: A/A peeking simulation on the real no-email customers. Writes reports/06a_peeking.md."""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from abtest.sequential import aa_peeking_false_positive_rate, obrien_fleming_boundaries  # noqa: E402

N_SIM, SEED = 2_000, 42
LOOKS = [1, 2, 5, 10, 20, 50, 100]
df = pd.read_csv(ROOT / "data" / "raw" / "hillstrom.csv")
ctrl = df[df.segment == "No E-Mail"]
n_arm = len(ctrl) // 2

out = ["# Step 6a: the cost of peeking (A/A simulation)", "",
       "Generated by `python scripts/peeking_simulation.py`.", "",
       f"Each simulated test takes the {len(ctrl):,} real **no-email** customers, shuffles them and splits "
       f"them into two arms of {n_arm:,}. Nobody got an email, so any 'significant' difference is a false "
       f"positive. An analyst checks the z-test at equally spaced points and stops at the first p < 0.05. "
       f"{N_SIM:,} simulations per row, seed {SEED}. Monte Carlo standard error at 5% is about "
       f"{np.sqrt(0.05 * 0.95 / N_SIM):.1%}.", "",
       "With O'Brien-Fleming boundaries the critical value is very strict early and close to 1.96 at the "
       "end; the constant is calibrated so the overall false-positive rate is 5%.", "",
       "| Looks | Naive false-positive rate (conversion) | Naive (visit) | O'Brien-Fleming (conversion) | O'Brien-Fleming (visit) | First / last OBF boundary |",
       "|---|---|---|---|---|---|"]
for k in LOOKS:
    b = obrien_fleming_boundaries(k, seed=SEED)
    r = {}
    for m in ("conversion", "visit"):
        y = ctrl[m].to_numpy()
        r[m, "naive"] = aa_peeking_false_positive_rate(y, k, N_SIM, seed=SEED)
        r[m, "obf"] = aa_peeking_false_positive_rate(y, k, N_SIM, boundaries=b, seed=SEED)
    line = (f"| {k} | {r['conversion', 'naive']:.1%} | {r['visit', 'naive']:.1%} | {r['conversion', 'obf']:.1%} "
            f"| {r['visit', 'obf']:.1%} | {b[0]:.2f} / {b[-1]:.2f} |")
    out.append(line)
    print(line, flush=True)
out += ["", "**Reading it:** one look gives about the promised 5%. Checking the same test repeatedly and stopping "
        "at the first significant result multiplies the false-positive rate, even though the data and the "
        "test are exactly the same. A pre-set group-sequential boundary (or simply fixing the sample size "
        "in advance and looking once) brings it back to about 5%.", "",
        "The single-look rates differ from 5% by no more than about 2 Monte Carlo standard errors. Conversion "
        "has only about 61 buyers per arm here, so its z-test rests on a rougher normal approximation than "
        "visit (about 1,130 visitors per arm). The 5-look OBF constant (2.04 at the last look) matches the "
        "published O'Brien-Fleming value.", ""]
text = "\n".join(out)
(ROOT / "reports" / "06a_peeking.md").write_text(text, encoding="utf-8", newline="\n")
print(text)
