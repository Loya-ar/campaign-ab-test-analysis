"""Step 2: power analysis. Baselines are taken from the no-email group, standing in for
the historical rates a team would use before launching the test."""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from abtest.power import mde_proportions, n_per_group_means, n_per_group_proportions  # noqa: E402

DATA = Path(__file__).resolve().parents[1] / "data" / "raw" / "hillstrom.csv"
POWER = 0.8
ALPHA_PLAN = 0.025  # 0.05 split over 2 comparisons (Bonferroni bound on Holm's first step)

lines: list[str] = ["# Step 2: power analysis", "", "Generated by `python scripts/design_power.py`. See docs/design.md for the reading.", ""]


def say(text: str = "") -> None:
    print(text)
    lines.extend(text.split("\n"))


df = pd.read_csv(DATA)
ctrl = df[df.segment == "No E-Mail"]
n_avail = int(df.segment.value_counts().min())
p_conv, p_visit = ctrl.conversion.mean(), ctrl.visit.mean()
sd_spend = ctrl.spend.std()
say(f"Baselines (no-email group): conversion {p_conv:.4%}, visit {p_visit:.4%}, "
      f"spend mean ${ctrl.spend.mean():.4f}, SD ${sd_spend:.4f}; smallest arm n={n_avail:,}\n")

say("Conversion: customers per group for a relative lift (power 0.8)\n")
say("| Relative lift | Treatment rate | n/group (alpha 0.05) | n/group (alpha 0.025) |")
say("|---|---|---|---|")
for rel in [0.10, 0.20, 0.30, 0.50, 1.00]:
    p_t = p_conv * (1 + rel)
    say(f"| +{rel:.0%} | {p_t:.4%} | {n_per_group_proportions(p_conv, p_t, 0.05, POWER):,} "
          f"| {n_per_group_proportions(p_conv, p_t, ALPHA_PLAN, POWER):,} |")

say(f"\nMDE with n={n_avail:,} per group (power 0.8)\n")
say("| Metric | Baseline | alpha | Absolute MDE | Relative MDE |")
say("|---|---|---|---|---|")
for name, p in [("conversion", p_conv), ("visit", p_visit)]:
    for a in (0.05, ALPHA_PLAN):
        d = mde_proportions(p, n_avail, a, POWER)
        say(f"| {name} | {p:.4%} | {a} | {d*100:.3f} pp | {d/p:.1%} |")

# Spend: solve the means formula for delta given n (closed form).
from scipy.stats import norm  # noqa: E402
for a in (0.05, ALPHA_PLAN):
    d = (norm.ppf(1 - a / 2) + norm.ppf(POWER)) * sd_spend * (2 / n_avail) ** 0.5
    say(f"| spend/customer | ${ctrl.spend.mean():.3f} | {a} | ${d:.3f} | {d/ctrl.spend.mean():.1%} |")
say(f"\n- Check: spend n/group for +$0.50 at alpha 0.025: {n_per_group_means(sd_spend, 0.5, ALPHA_PLAN):,}")

# Cross-check against statsmodels (Cohen's h, arcsine transform)
from statsmodels.stats.power import NormalIndPower  # noqa: E402
from statsmodels.stats.proportion import proportion_effectsize  # noqa: E402
h = proportion_effectsize(p_conv * 1.3, p_conv)
say(f"- Cross-check +30% conversion, alpha 0.025: ours {n_per_group_proportions(p_conv, p_conv*1.3, ALPHA_PLAN):,} "
      f"vs statsmodels (Cohen's h) {NormalIndPower().solve_power(h, alpha=ALPHA_PLAN, power=POWER):,.0f}")

(DATA.parents[2] / "reports" / "02_power.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
