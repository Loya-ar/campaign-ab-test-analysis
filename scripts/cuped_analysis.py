"""Step 5: CUPED with pre-period `history`. Writes reports/05_cuped.md."""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from abtest.cuped import cuped_adjust, cuped_theta  # noqa: E402
from abtest.inference import welch_test  # noqa: E402

TREATMENTS = {"Men's email": "Mens E-Mail", "Women's email": "Womens E-Mail"}
METRICS = {"conversion": ("Conversion", 100, "pp"), "visit": ("Visit", 100, "pp"), "spend": ("Spend per customer", 1, "$")}
df = pd.read_csv(ROOT / "data" / "raw" / "hillstrom.csv")
dummies = pd.get_dummies(df[["zip_code", "channel"]], drop_first=True, dtype=float)
COVS = pd.concat([df[["recency", "history", "mens", "womens", "newbie"]].astype(float), dummies], axis=1)


def fmt(v, scale, unit):
    return f"${v:+.3f}" if unit == "$" else f"{v*scale:+.3f} pp"


out = ["# Step 5: CUPED", "", "Generated by `python scripts/cuped_analysis.py`.", "",
       "CUPED replaces each outcome y with y − θ(x − x̄), where x is pre-period `history` (dollars spent "
       "in the past year) and θ = cov(y, x) / var(x) is estimated on treatment and control pooled. "
       "The point estimate stays unbiased because x was fixed before randomisation; the variance falls "
       "by about ρ², where ρ is the correlation between y and x.", "",
       "As a comparison, the last columns use **regression adjustment** with all 11 pre-period "
       "features (OLS of y on treatment + centred covariates, HC1 robust standard errors). This is "
       "CUPED generalised to several covariates.", "",
       "| Metric | Email | ρ(y, history) | θ | Raw lift (95% CI) | CUPED lift (95% CI) | Variance reduction | CI width change | Regression-adjusted lift (95% CI) | CI width change |",
       "|---|---|---|---|---|---|---|---|---|---|"]
summary = []
for m, (mname, scale, unit) in METRICS.items():
    for label, seg in TREATMENTS.items():
        sub = df[df.segment.isin([seg, "No E-Mail"])]
        y, x = sub[m].to_numpy(float), sub.history.to_numpy(float)
        treat = (sub.segment == seg).to_numpy()
        theta = cuped_theta(y, x)
        y_adj = cuped_adjust(y, x, theta)
        raw = welch_test(y[treat], y[~treat])
        adj = welch_test(y_adj[treat], y_adj[~treat])
        # variance reduction within groups (what drives the SE)
        vr = 1 - (y_adj[treat].var(ddof=1) / len(y[treat]) + y_adj[~treat].var(ddof=1) / len(y[~treat])) / (
            y[treat].var(ddof=1) / len(y[treat]) + y[~treat].var(ddof=1) / len(y[~treat]))
        w_raw = raw.ci_diff[1] - raw.ci_diff[0]
        w_adj = adj.ci_diff[1] - adj.ci_diff[0]
        Xc = COVS.loc[sub.index]
        X = sm.add_constant(pd.concat([pd.Series(treat.astype(float), index=sub.index, name="treat"),
                                       Xc - Xc.mean()], axis=1))
        fit = sm.OLS(y, X).fit(cov_type="HC1")
        lo, hi = fit.conf_int().loc["treat"]
        w_reg = hi - lo
        rho = np.corrcoef(y, x)[0, 1]
        out.append(
            f"| {mname} | {label} | {rho:.4f} | {theta:.3g} "
            f"| {fmt(raw.diff, scale, unit)} ({fmt(raw.ci_diff[0], scale, unit)}, {fmt(raw.ci_diff[1], scale, unit)}) "
            f"| {fmt(adj.diff, scale, unit)} ({fmt(adj.ci_diff[0], scale, unit)}, {fmt(adj.ci_diff[1], scale, unit)}) "
            f"| {vr:.2%} | {w_adj / w_raw - 1:+.2%} "
            f"| {fmt(fit.params['treat'], scale, unit)} ({fmt(lo, scale, unit)}, {fmt(hi, scale, unit)}) "
            f"| {w_reg / w_raw - 1:+.2%} |")
        summary.append((mname, label, rho, vr, w_adj / w_raw - 1, w_reg / w_raw - 1))

# Sample size equivalent: variance reduction r means the same precision with (1 - r) of the customers.
best = max(summary, key=lambda s: s[3])
out += ["", "## Reading the table", "",
        f"- Largest CUPED variance reduction: **{best[3]:.2%}** ({best[0]}, {best[1]}), equivalent to "
        f"running the test with {best[3]:.1%} fewer customers for the same precision.",
        "- Variance reduction ≈ ρ², so a covariate only helps as much as it correlates with the outcome. "
        "Past-year spend correlates only weakly with buying in a 2-week window, because purchases are rare.",
        ""]

text = "\n".join(out)
(ROOT / "reports" / "05_cuped.md").write_text(text, encoding="utf-8", newline="\n")
print(text)


# --- Simulation: does the implementation deliver the theory when the covariate is strong? -----
# Metrics like account balances or monthly card spend are much more stable over time than a
# 2-week purchase flag, so rho is high. Check: variance reduction ~ rho^2, no bias, 95% coverage.
rng = np.random.default_rng(7)
N_SIM, N_ARM, EFFECT = 2_000, 2_000, 0.1  # effect in SD units of y
sim = ["", "## Simulation: CUPED with a strongly correlated covariate", "",
       f"{N_SIM:,} simulated experiments per row, {N_ARM:,} customers per arm, true effect {EFFECT} SD, "
       "covariate x and outcome y bivariate normal with correlation ρ. Seed 7.", "",
       "| ρ | Theory: variance reduction ρ² | Simulated variance reduction | Mean estimate raw | Mean estimate CUPED | 95% CI coverage CUPED |",
       "|---|---|---|---|---|---|"]
for rho in (0.0, 0.3, 0.5, 0.7, 0.9):
    est_raw, est_cup, cover = np.empty(N_SIM), np.empty(N_SIM), 0
    for i in range(N_SIM):
        x = rng.standard_normal(2 * N_ARM)
        y = rho * x + np.sqrt(1 - rho**2) * rng.standard_normal(2 * N_ARM)
        t = np.arange(2 * N_ARM) < N_ARM
        y = y + EFFECT * t
        ya = cuped_adjust(y, x)
        est_raw[i] = y[t].mean() - y[~t].mean()
        r = welch_test(ya[t], ya[~t])
        est_cup[i] = r.diff
        cover += r.ci_diff[0] <= EFFECT <= r.ci_diff[1]
    sim.append(f"| {rho} | {rho**2:.0%} | {1 - est_cup.var() / est_raw.var():.1%} | {est_raw.mean():.4f} "
               f"| {est_cup.mean():.4f} | {cover / N_SIM:.1%} |")
sim += ["", "The implementation matches theory when the covariate is strong. On Hillstrom the covariate is "
        "simply weak for these outcomes.", ""]
with (ROOT / "reports" / "05_cuped.md").open("a", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(sim))
print("\n".join(sim))
